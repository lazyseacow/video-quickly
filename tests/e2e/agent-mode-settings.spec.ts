test('uses the shared creation Skill on an existing project and respects clearing the inherited selection', async ({ page, request }, info) => {
  const source = await productionFixture(request), workflow = source.project.workflow;
  const archive = info.outputPath('creation-skills.zip');
  await writeFile(archive, zipSync({ 'planning/SKILL.md': strToU8('---\nname: planning-method\ndescription: 旧项目的创作方法\n---\n保持镜头叙事连续。') }));
  const { skills } = await importSkillFixture((method, params) => rpc(request, method, params), { path: archive });
  const project = await rpc<ProjectDocument>(request, 'project.update', { projectId: source.project.id, revision: source.project.revision, patch: { workflow: {
    ...workflow,
    production: { ...workflow.production, agentInheritsPlanningSkills: undefined },
    nodes: workflow.nodes.map(node => ['brief', 'style', 'script'].includes(node.id) ? { ...node, skillIds: [skills[0].id] } : node),
  } } });
  expect(project.workflow.production.agentSkillIds).toEqual([]);
  const dialog = await openProduction(page, project);
  await pickProductionModel(dialog, '文本模型', source.text);
  await productionStep(dialog, '确认保存');
  const inherited = dialog.getByText('沿用 1 个 Skill · 工具自动选择', { exact: true });
  await expect(inherited).toBeVisible();
  await saveProduction(dialog); await expect(dialog).toHaveCount(0);

  await page.getByRole('button', { name: '制作设置', exact: true }).click();
  await productionStep(dialog, '创作要求');
  await dialog.getByText('剪辑 Agent 设置', { exact: true }).click();
  const picker = dialog.getByRole('group', { name: '剪辑 Agent 的 Skill', exact: true });
  const trigger = picker.getByRole('button', { name: '剪辑 Agent 的 Skill', exact: true });
  await expect(trigger).toContainText('沿用 1 个');
  await trigger.click();
  await picker.getByRole('button', { name: '清空选择', exact: true }).click();
  await expect(trigger).toContainText('自动选择');
  await saveProduction(dialog); await expect(dialog).toHaveCount(0);
  expect((await source.saved()).workflow.production).toMatchObject({ agentSkillIds: [], agentInheritsPlanningSkills: false });

  await page.getByRole('button', { name: '制作设置', exact: true }).click();
  await productionStep(dialog, '确认保存');
  await expect(inherited).toHaveCount(0);
});

test('saves multiple MCP bindings on an ordinary Agent task from advanced task settings', async ({ page, request }) => {
  const source = await productionFixture(request), connections: MCPServer[] = [];
  for (const suffix of ['a', 'b']) connections.push(await rpc<MCPServer>(request, 'tool.register', { server: { name: `任务工具 ${source.project.id}-${suffix}`, transport: 'http', url: 'http://127.0.0.1:1/mcp', enabled: true } }));
  const project = await rpc<ProjectDocument>(request, 'project.update', { projectId: source.project.id, revision: source.project.revision, patch: { workflow: { ...source.project.workflow, id: `agent-task-${source.project.id}`, stages: undefined, nodes: [{ id: 'agent-task', kind: 'agent', label: '独立 Agent 任务', modelId: source.text.id }], edges: [] } } });
  const dialog = await openProduction(page, project);
  await dialog.locator('[data-production-step="planning"] > .production-settings__advanced > summary').click();
  const tools = dialog.getByRole('group', { name: '使用工具连接', exact: true });
  await expect(tools).toContainText('留空由 Agent 按任务自动选择');
  for (const connection of connections) await tools.getByRole('checkbox', { name: connection.name, exact: true }).check();
  await saveProduction(dialog); await expect(dialog).toHaveCount(0);
  expect((await source.saved()).workflow.nodes[0].config.mcpServerIds).toEqual(connections.map(connection => connection.id));
});
